/// Build-time configuration for the yopet client.
///
/// Two values are read at compile time via `--dart-define`:
///   * `SUPABASE_URL` — base URL of the local Supabase instance.
///   * `SUPABASE_PUBLISHABLE_KEY` — opaque client-side key (matches
///     the key supabase_flutter 2.17+ calls `publishableKey:`).
///
/// `run-dev.ps1` is the development wrapper that picks the right URL
/// for the chosen target (Windows localhost vs Android emulator
/// `10.0.2.2`) and forwards both values via dart-define.
///
/// Defaults are tuned for a *clean Linux dev box*. The dev environment
/// at `~/myworkspace/.../yopet` (Windows, Docker Desktop, WSL2 NAT
/// cache pinning port 54321) is the `run-dev.ps1` override path.
class Env {
  Env._();

  /// Supabase API base URL. Default = the upstream self-host standard
  /// (port 54321, no offset). The dev wrapper overrides this to
  /// `54331` (see `docs/setup/local-supabase.md` §11.1 for why).
  static const String supabaseUrl = String.fromEnvironment(
    'SUPABASE_URL',
    defaultValue: 'http://localhost:54321',
  );

  /// Supabase publishable (client-side) key. Empty default forces
  /// explicit dart-define at run time and keeps the secret out of
  /// the source tree.
  ///
  /// Supabase's older `anonKey:` was deprecated in supabase_flutter
  /// 2.17 in favour of `publishableKey:`, which expects the new
  /// opaque `sb_publishable_...` token (generated by
  /// `add-new-auth-keys.sh --update-env`).
  static const String supabasePublishableKey = String.fromEnvironment(
    'SUPABASE_PUBLISHABLE_KEY',
    defaultValue: '',
  );
}
