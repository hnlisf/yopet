# yopet run-dev.ps1
# Wrapper that reads the local runtime's ../supabase-local/docker/.env and
# starts flutter run with correct SUPABASE_URL / SUPABASE_ANON_KEY dart-defines.
#
# The sibling runtime is not a source of Yopet schema. Domain migrations, seed
# data, and database tests are owned by .\supabase; see
# docs/setup/database-workflow.md.
#
# Usage:
#   .\run-dev.ps1                    # default: Windows desktop, URL from .env
#   .\run-dev.ps1 -Platform android   # Android emulator: host translated to 10.0.2.2
#   .\run-dev.ps1 -Platform web       # local browser preview with the same auth config
#   .\run-dev.ps1 -Platform ios       # iOS simulator/device on macOS
#   .\run-dev.ps1 -Platform macos     # macOS desktop
#   .\run-dev.ps1 -Platform linux     # Linux desktop
#   .\run-dev.ps1 -Platform web -WebPort 4196
#   .\run-dev.ps1 -Url http://example:54321  # override URL (debug)
#
# Prerequisites:
#   - Flutter SDK installed and on PATH (`flutter --version` works)
#   - Supabase stack running (see ../supabase-local/docker/README and
#     docs/setup/local-supabase.md)

[CmdletBinding()]
param(
    [ValidateSet('windows', 'android', 'ios', 'linux', 'macos', 'web')]
    [string]$Platform = 'windows',

    [string]$Url = '',

    [ValidateRange(1024, 65535)]
    [int]$WebPort = 4196,

    # Build a Windows release against the same local backend, without launching.
    [switch]$BuildOnly,

    [string]$FlutterPath = 'flutter',

    # Use already resolved dependencies for repeatable local build/test runs.
    [switch]$NoPub
)

$ErrorActionPreference = 'Stop'
if ($BuildOnly -and $Platform -ne 'windows') {
    throw '-BuildOnly currently supports -Platform windows only.'
}

# ---------------------------------------------------------------------------
# 1. Resolve the .env path (relative to this script's location)
# ---------------------------------------------------------------------------
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$envPath = Join-Path $scriptDir '..\supabase-local\docker\.env'

if (-not (Test-Path $envPath)) {
    Write-Error "Cannot find Supabase .env at: $envPath`nRun F1 first (see docs/setup/local-supabase.md). Aborting."
    exit 1
}

# ---------------------------------------------------------------------------
# 2. Parse .env (simple key=value parser, supports # comments and quoted vals)
# ---------------------------------------------------------------------------
function Read-EnvValue {
    param([string]$Path, [string]$Key)
    Get-Content $Path | ForEach-Object {
        $line = $_.Trim()
        if ($line -match '^(?!\s*#)(?!\s*$)') {
            $kv = $line -split '=', 2
            if ($kv.Count -eq 2 -and $kv[0].Trim() -eq $Key) {
                return $kv[1].Trim().Trim('"').Trim("'")
            }
        }
    }
}

$envSupabaseUrl = Read-EnvValue -Path $envPath -Key 'SUPABASE_PUBLIC_URL'
$envKongPort     = Read-EnvValue -Path $envPath -Key 'KONG_HTTP_PORT'
# Use the new opaque publishable key (sb_publishable_...) generated by
# supabase-local/docker/utils/add-new-auth-keys.sh --update-env. Falls back
# to legacy ANON_KEY only if the publishable key is not present in .env.
$envPublishableKey = Read-EnvValue -Path $envPath -Key 'SUPABASE_PUBLISHABLE_KEY'
if (-not $envPublishableKey) {
    $envPublishableKey = Read-EnvValue -Path $envPath -Key 'ANON_KEY'
}

# ---------------------------------------------------------------------------
# 3. Resolve URL: -Url override > local gateway port > SUPABASE_PUBLIC_URL
# ---------------------------------------------------------------------------
if ($Url -ne '') {
    $supabaseUrl = $Url
} elseif ($envSupabaseUrl) {
    $parsedSupabaseUrl = [System.UriBuilder]::new($envSupabaseUrl)
    # Docker Desktop may expose Kong on an offset host port while the copied
    # SUPABASE_PUBLIC_URL still names the upstream default (54321). The local
    # KONG_HTTP_PORT is the authoritative browser-facing port in that case.
    if (
        $envKongPort -and
        ($parsedSupabaseUrl.Host -eq 'localhost' -or $parsedSupabaseUrl.Host -eq '127.0.0.1')
    ) {
        $parsedSupabaseUrl.Port = [int]$envKongPort
    }
    $supabaseUrl = $parsedSupabaseUrl.Uri.GetLeftPart([System.UriPartial]::Authority)
} else {
    $port = if ($envKongPort) { $envKongPort } else { '54321' }
    $supabaseUrl = "http://localhost:${port}"
}

if (-not $envPublishableKey) {
    Write-Error "SUPABASE_PUBLISHABLE_KEY (or fallback ANON_KEY) not found in $envPath.`nF1 stack must be up and `.env` must contain a valid client-side key. Aborting."
    exit 1
}

# ---------------------------------------------------------------------------
# 4. Translate URL host for Android emulator
# ---------------------------------------------------------------------------
if ($Platform -eq 'android') {
    # Android emulator routes 10.0.2.2 -> host machine's localhost
    $parsed = [System.UriBuilder]::new($supabaseUrl)
    if ($parsed.Host -eq 'localhost' -or $parsed.Host -eq '127.0.0.1') {
        $parsed.Host = '10.0.2.2'
    }
    $supabaseUrl = $parsed.Uri.ToString()
}

# ---------------------------------------------------------------------------
# 5. Map Platform to flutter run -d target
# ---------------------------------------------------------------------------
$flutterTarget = switch ($Platform) {
    'windows' { 'windows' }
    'android' { 'android' }
    'ios'     { 'ios' }
    'linux'   { 'linux' }
    'macos'   { 'macos' }
    'web'     { 'web-server' }
}

# ---------------------------------------------------------------------------
# 6. Run flutter
# ---------------------------------------------------------------------------
Write-Host "yopet dev launcher" -ForegroundColor Cyan
Write-Host "  Platform: $Platform  (flutter -d $flutterTarget)"
Write-Host "  URL:      $supabaseUrl"
Write-Host "  PublishableKey: configured"
Write-Host ""

$flutterArgs = @(
    'run',
    '-d', $flutterTarget,
    "--dart-define=SUPABASE_URL=$supabaseUrl",
    "--dart-define=SUPABASE_PUBLISHABLE_KEY=$envPublishableKey"
)

if ($BuildOnly) {
    $flutterArgs = @(
        'build', 'windows', '--release',
        "--dart-define=SUPABASE_URL=$supabaseUrl",
        "--dart-define=SUPABASE_PUBLISHABLE_KEY=$envPublishableKey"
    )
}

if ($Platform -eq 'web') {
    $flutterArgs += "--web-port=$WebPort"
}

if ($NoPub) {
    $flutterArgs += '--no-pub'
}

Push-Location $scriptDir
try {
    & $FlutterPath @flutterArgs
} finally {
    Pop-Location
}
if ($LASTEXITCODE -ne 0) {
    throw "Flutter command failed with exit code $LASTEXITCODE."
}
